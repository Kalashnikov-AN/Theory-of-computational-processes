package zabsu.n_threads_integration;

/**
 * Интерфейс для вычисления частичной суммы при численном интегрировании
 *
 * <p>Предназначен для классов, реализующих один из шагов
 * параллельного интегрирования: вычисление суммы значений функции
 * на заданном участке разбиения</p>
 */
@FunctionalInterface
public interface PartialSumCalculator {

    /**
     * Вычисляет частичную сумму значений функции на участке разбиения [start, end).

     * @param model модель задачи, содержащая функцию f(x) и параметры интегрирования;
     *
     * @param a     левая граница всего интервала интегрирования;
     * используется как точка отсчёта для вычисления x = a + i*h
     *
     * @param h     шаг интегрирования, равный (b - a) / n;
     *
     * @param start индекс первого разбиения участка (включительно);
     *
     * @param end   индекс последнего разбиения участка (не включая);
     *
     * @return вычисленная частичная сумма значений функции
     */
    double computePartialSum(IntegrationModel model, double a, double h, int start, int end);
}
